#!/usr/bin/env python3
"""Build a lightweight character manifest for LilyAi's Umamusume knowledge base.

The manifest is derived from character Markdown files, so it does not duplicate
facts that may become stale. It is intentionally dependency-free and writes a
small, predictable YAML document that humans can review easily.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path
from typing import Iterable

DEFAULT_CHARACTER_DIR = Path("LilyAiGameSpace/Umamusume/Character")
DEFAULT_OUTPUT = DEFAULT_CHARACTER_DIR / "index.yaml"
EXCLUDED_FILES = {"CharacterList.md", "index.md", "README.md"}


def display_name(path: Path, text: str) -> str:
    match = re.search(r"^#\s+(.+?)\s*$", text, re.MULTILINE)
    if match:
        title = re.sub(r"\s*\|.*$", "", match.group(1)).strip()
        if title and not title.startswith("Wiki source:"):
            return title
    return path.stem.replace("_", " ")


def japanese_name(text: str) -> str | None:
    match = re.search(r"^\*\*Japanese name:\*\*\s*(.+?)\s*$", text, re.MULTILINE)
    if not match:
        return None
    value = match.group(1).strip()
    return value.split("(", 1)[0].strip() or None


def stable_id(path: Path) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", path.stem.lower()).strip("-")
    return f"character.{slug}"


def aliases(path: Path, name: str, jp_name: str | None) -> list[str]:
    values = [name, path.stem.replace("_", " ")]
    if jp_name:
        values.append(jp_name)
    result: list[str] = []
    for value in values:
        if value and value not in result:
            result.append(value)
    return result


def iter_entries(character_dir: Path) -> Iterable[dict[str, object]]:
    for path in sorted(character_dir.glob("*.md"), key=lambda item: item.name.casefold()):
        if path.name in EXCLUDED_FILES or path.name.startswith((".", "_")):
            continue
        text = path.read_text(encoding="utf-8")
        name = display_name(path, text)
        yield {
            "character_id": stable_id(path),
            "canonical_name": name,
            "aliases": aliases(path, name, japanese_name(text)),
            "markdown": path.name,
        }


def yaml_quote(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def render(entries: Iterable[dict[str, object]]) -> str:
    rows = list(entries)
    lines = [
        "# Generated by tools/build_character_index.py; do not edit by hand.",
        "schema_version: 1",
        "document_role: character_manifest",
        "source_directory: LilyAiGameSpace/Umamusume/Character",
        "characters:",
    ]
    for entry in rows:
        lines.extend([
            f"  - character_id: {yaml_quote(str(entry['character_id']))}",
            f"    canonical_name: {yaml_quote(str(entry['canonical_name']))}",
            "    aliases:",
        ])
        for alias in entry["aliases"]:  # type: ignore[union-attr]
            lines.append(f"      - {yaml_quote(str(alias))}")
        lines.append(f"    markdown: {yaml_quote(str(entry['markdown']))}")
    return "\n".join(lines) + "\n"


def build(character_dir: Path, output: Path, check: bool = False) -> bool:
    generated = render(iter_entries(character_dir))
    existing = output.read_text(encoding="utf-8") if output.exists() else None
    if check:
        return existing == generated
    output.write_text(generated, encoding="utf-8")
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--character-dir", type=Path, default=DEFAULT_CHARACTER_DIR)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true", help="fail if the committed index is stale")
    args = parser.parse_args()
    if args.check and not build(args.character_dir, args.output, check=True):
        print(f"Character index is stale: {args.output}")
        return 1
    if not args.check:
        build(args.character_dir, args.output)
        print(f"Wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
